"""PreToolUse hook: everything but the docs and the workflow is generated; refuse edits (exit 2 = block, stderr goes to Claude)."""
import json
import os
import sys
from pathlib import Path

HAND_WRITTEN = ("README.md", "AGENTS.md", "CLAUDE.md", ".gitattributes", ".github/", ".claude/")

event = json.load(sys.stdin)
path = event.get("tool_input", {}).get("file_path")
if not path:
    sys.exit(0)
root = Path(os.environ.get("CLAUDE_PROJECT_DIR") or event.get("cwd") or ".").resolve()
try:
    rel = Path(path).resolve().relative_to(root).as_posix()
except ValueError:
    sys.exit(0)
if not rel.startswith(HAND_WRITTEN):
    print(f"Blocked: {rel} is generated by the sync workflow from the code in a3ref/a3ref.github.io. "
          "Fix the parser there (biwiki/), or the text on the wiki itself.", file=sys.stderr)
    sys.exit(2)
